/**
 * A minimal sRGB colour profile (ICC v2.1, matrix and tone-curve type), generated here so that nothing is copied from
 * another program or standard profile. It is what a PDF/A file's output intent points at. Primaries are the sRGB ones
 * adapted to the D50 profile connection space; the tone curve is the sRGB transfer function sampled at 1024 points.
 */

const s15 = (v: number) => Math.round(v * 65536)

class Writer {
  private chunks: number[] = []
  u8(v: number) {
    this.chunks.push(v & 255)
    return this
  }
  u16(v: number) {
    return this.u8(v >> 8).u8(v)
  }
  u32(v: number) {
    return this.u8(v >>> 24).u8(v >>> 16).u8(v >>> 8).u8(v)
  }
  i32(v: number) {
    return this.u32(v >>> 0)
  }
  sig(s: string) {
    for (const ch of s) this.u8(ch.charCodeAt(0))
    return this
  }
  zeros(n: number) {
    for (let i = 0; i < n; i++) this.u8(0)
    return this
  }
  get length() {
    return this.chunks.length
  }
  pad4() {
    while (this.chunks.length % 4) this.u8(0)
    return this
  }
  bytes() {
    return Uint8Array.from(this.chunks)
  }
}

const xyz = (x: number, y: number, z: number) => new Writer().sig('XYZ ').zeros(4).i32(s15(x)).i32(s15(y)).i32(s15(z)).pad4().bytes()

function text(s: string): Uint8Array {
  return new Writer().sig('text').zeros(4).sig(s).u8(0).pad4().bytes()
}

function desc(s: string): Uint8Array {
  const w = new Writer().sig('desc').zeros(4).u32(s.length + 1).sig(s).u8(0)
  // Unicode and Macintosh descriptions are left empty.
  w.u32(0).u32(0).u16(0).u8(0).zeros(67)
  return w.pad4().bytes()
}

function curve(): Uint8Array {
  const n = 1024
  const w = new Writer().sig('curv').zeros(4).u32(n)
  for (let i = 0; i < n; i++) {
    const x = i / (n - 1)
    const y = x <= 0.04045 ? x / 12.92 : Math.pow((x + 0.055) / 1.055, 2.4)
    w.u16(Math.round(y * 65535))
  }
  return w.pad4().bytes()
}

/** The profile's bytes, with the creation date given (so output is repeatable in tests). */
export function srgbIccProfile(date = new Date()): Uint8Array {
  const trc = curve()
  const tags: [string, Uint8Array][] = [
    ['cprt', text('Generated by OpenPDF. No copyright; free to use.')],
    ['desc', desc('sRGB IEC61966-2.1 (generated)')],
    ['wtpt', xyz(0.9642, 1.0, 0.8249)],
    ['rXYZ', xyz(0.43607, 0.22249, 0.01392)],
    ['gXYZ', xyz(0.38515, 0.71687, 0.09708)],
    ['bXYZ', xyz(0.14307, 0.06061, 0.7141)]
  ]
  const table = new Writer()
  const body = new Writer()
  const headerAndTable = 128 + 4 + 12 * (tags.length + 3)
  let offset = headerAndTable
  const place = (sig: string, data: Uint8Array) => {
    table.sig(sig).u32(offset).u32(data.length)
    for (const b of data) body.u8(b)
    offset += data.length
  }
  for (const [sig, data] of tags) place(sig, data)
  // The three tone curves are the same data, stored once and referred to three times.
  const trcAt = offset
  for (const b of trc) body.u8(b)
  offset += trc.length
  for (const sig of ['rTRC', 'gTRC', 'bTRC']) table.sig(sig).u32(trcAt).u32(trc.length)

  const h = new Writer()
  h.u32(offset) // total size
    .zeros(4) // preferred CMM
    .u32(0x02100000) // version 2.1.0
    .sig('mntr')
    .sig('RGB ')
    .sig('XYZ ')
    .u16(date.getUTCFullYear())
    .u16(date.getUTCMonth() + 1)
    .u16(date.getUTCDate())
    .u16(date.getUTCHours())
    .u16(date.getUTCMinutes())
    .u16(date.getUTCSeconds())
    .sig('acsp')
    .sig('MSFT')
    .zeros(4) // flags
    .zeros(4) // device manufacturer
    .zeros(4) // device model
    .zeros(8) // attributes
    .u32(0) // rendering intent: perceptual
    .i32(s15(0.9642))
    .i32(s15(1.0))
    .i32(s15(0.8249)) // illuminant D50
    .zeros(4) // creator
    .zeros(16) // profile ID
    .zeros(28)
  const out = new Writer()
  for (const b of h.bytes()) out.u8(b)
  out.u32(tags.length + 3)
  for (const b of table.bytes()) out.u8(b)
  for (const b of body.bytes()) out.u8(b)
  return out.bytes()
}
