/**
 * Writes THIRD_PARTY_NOTICES.md from the production dependency tree (node_modules package.json files).
 * Exits 1 if any production package has a copyleft (GPL/AGPL/LGPL/SSPL) or unknown licence.
 * Usage: npm run licences
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const nm = join(root, 'node_modules')
const readJson = p => JSON.parse(readFileSync(p, 'utf8'))

const pkgDir = name => join(nm, ...name.split('/'))
const seen = new Map()
function walk(name) {
  const dir = pkgDir(name)
  if (!existsSync(join(dir, 'package.json'))) return
  const pkg = readJson(join(dir, 'package.json'))
  const key = `${pkg.name}@${pkg.version}`
  if (seen.has(key)) return
  seen.set(key, { pkg, dir })
  for (const dep of Object.keys(pkg.dependencies ?? {})) walk(dep)
  for (const dep of Object.keys(pkg.optionalDependencies ?? {})) walk(dep)
}
for (const dep of Object.keys(readJson(join(root, 'package.json')).dependencies ?? {})) walk(dep)

const licenceOf = pkg => {
  const l = pkg.license ?? pkg.licenses
  if (!l) return ''
  if (typeof l === 'string') return l
  if (Array.isArray(l)) return l.map(x => x.type ?? x).join(' OR ')
  return l.type ?? ''
}
const BAD = /(^|[^A-Z])(A?GPL|LGPL|SSPL)/i
/** A dual-licensed package ("MIT OR GPL-3.0-or-later") is fine when one of its options is permissive: that is the one used. */
const options = lic => lic.replace(/[()]/g, '').split(/\s+OR\s+/i).map(x => x.trim()).filter(Boolean)
const usable = lic => options(lic).some(o => !BAD.test(o) && !/unknown|unlicensed|see license/i.test(o))
const elected = lic => options(lic).find(o => !BAD.test(o)) ?? lic
const bad = []
const entries = [...seen.values()].sort((a, b) => a.pkg.name.localeCompare(b.pkg.name))
let out = '# Third-party notices\n\nOpenPDF is MIT licensed (see LICENSE). It includes the following production dependencies. Generated by `npm run licences`; do not edit by hand.\n\n'
out += '## PDFium\n\n`@hyzyla/pdfium` bundles a WebAssembly build of PDFium. PDFium is licensed under the Apache License 2.0, with some bundled third-party parts under BSD-3-Clause and other permissive licences. The npm package does not ship PDFium\'s own licence texts (only the wrapper\'s MIT licence, reproduced below). Full texts: https://pdfium.googlesource.com/pdfium/+/refs/heads/main/LICENSE and https://pdfium.googlesource.com/pdfium/+/refs/heads/main/third_party/\n\n'
out += '## Packages\n\n'
for (const { pkg, dir } of entries) {
  const lic = licenceOf(pkg)
  if (!lic || !usable(lic)) bad.push(`${pkg.name}@${pkg.version}: ${lic || '(none)'}`)
  const file = readdirSync(dir).find(f => /^(licen[cs]e|copying)(\.|$)/i.test(f))
  out += `### ${pkg.name} ${pkg.version}\n\nLicence: ${lic || 'UNKNOWN'}${lic && options(lic).length > 1 ? ` (used under ${elected(lic)})` : ''}\n\n`
  out += file ? '```\n' + readFileSync(join(dir, file), 'utf8').trim() + '\n```\n\n' : '(No licence file in package.)\n\n'
}
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), out)
console.log(`Wrote THIRD_PARTY_NOTICES.md (${entries.length} packages)`)
if (bad.length) {
  console.error('Disallowed or unknown licences:\n' + bad.map(b => '  ' + b).join('\n'))
  process.exit(1)
}
